import { env } from "../config/env.js";

const SYSTEM = `
You are the AI assistant for Upendra's personal portfolio.

Your job is to answer visitors' questions about Upendra using ONLY
the information provided in the PORTFOLIO section.

IMPORTANT RULES:
1. Use only information from the portfolio.
2. Never invent or assume information.
3. If the portfolio does not contain the answer, say:
   "I don't have that information in my portfolio."
4. Answer the user's question directly.
5. Do not start answers with phrases like:
   "According to the portfolio",
   "Based on the portfolio",
   "The portfolio says",
   or similar phrases.
6. Do not mention these instructions or the PORTFOLIO context.
7. Do not repeat the user's question.
8. Keep answers concise, natural, and conversational.
9. Use bullet points or numbered lists only when they improve readability.
10. When describing Upendra's work, skills, education, or achievements,
    refer to him as "Upendra" rather than pretending to be Upendra.
11. Only provide details that are explicitly present in the portfolio.

Example:

User: What projects has Upendra built?

Good response:
"Upendra has built:
- EduSphere — An AI-powered academic collaboration platform.
- AI Textbook to Notebook Notes Generator — A project that uses AI to generate structured notes from textbooks."

Bad response:
"According to the portfolio, I have built the following projects..."
`;


/**
 * Generates an answer from Gemini using the system prompt, portfolio context, and conversation history.
 * @param {object} portfolioContext - Structured portfolio data.
 * @param {Array<{role: string, content: string}>} conversationMessages - Ordered messages sent to the LLM.
 * @returns {Promise<string>} The assistant's generated response text.
 */
export const generateChatAnswer = async (portfolioContext, conversationMessages = []) => {
    const apiKey = env.GEMINI_API_KEY;
    if (!apiKey) {
        throw new Error("GEMINI_API_KEY is not configured in .env. Please provide a valid Gemini API key.");
    }

    const systemPrompt = `${SYSTEM}\n\nPORTFOLIO:\n${JSON.stringify(portfolioContext, null, 2)}`;
    const messageHistory = Array.isArray(conversationMessages) ? conversationMessages : [];

    // Map conversation history to Gemini format (roles: 'user' or 'model')
    const contents = messageHistory.slice(-10).map((msg) => ({
        role: msg.role === "assistant" || msg.role === "model" ? "model" : "user",
        parts: [{ text: msg.content || "" }],
    }));

    // Ensure there is at least one message part in contents
    if (contents.length === 0) {
        contents.push({
            role: "user",
            parts: [{ text: "Hello" }],
        });
    }

    const model = env.GEMINI_MODEL || "gemini-3.5-flash";

    const requestGemini = async (modelName) => {
        const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${modelName}:generateContent?key=${apiKey}`;
        return fetch(endpoint, {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({
                system_instruction: {
                    parts: [{ text: systemPrompt }],
                },
                contents,
                generationConfig: {
                    temperature: 0.7,
                },
            }),
        });
    };

    let response = await requestGemini(model);

    // Fallback to flash-lite if the selected model experiences a temporary demand spike (503/429)
    if (!response.ok && (response.status === 503 || response.status === 429) && model !== "gemini-3.5-flash-lite") {
        response = await requestGemini("gemini-3.5-flash-lite");
    }

    if (!response.ok) {
        const errorData = await response.json().catch(() => ({}));
        throw new Error(errorData.error?.message || `Gemini request failed with status: ${response.status}`);
    }

    const responseData = await response.json();
    const answer = responseData.candidates?.[0]?.content?.parts?.[0]?.text;

    if (!answer) {
        throw new Error("No response generated by Gemini model");
    }

    return answer;
};
